import { build } from "esbuild";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const source = join(process.cwd(), "src", "mcp-widget");
export const generatedWidgetPath = join(
  process.cwd(),
  "src",
  "generated",
  "itinerary-widget.ts",
);

/** Bundles the MCP Apps itinerary card into one self-contained HTML document. */
export async function buildWidgetModule() {
  const bundle = await build({
    entryPoints: [join(source, "itinerary-widget.ts")],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    write: false,
  });
  const script = bundle.outputFiles[0].text.replace(
    /<\/script/gi,
    "<\\/script",
  );
  const css = readFileSync(join(source, "itinerary-widget.css"), "utf8");
  const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Sanaa Kenya itinerary</title><style>${css}</style></head><body><div id="root"></div><script type="module">${script}</script></body></html>`;
  return `// Generated by scripts/build-widget.ts from src/mcp-widget. Do not edit; run npm run build:widget.\nexport const itineraryWidgetHtml = ${JSON.stringify(html)};\n`;
}
